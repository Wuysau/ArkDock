import { createHash } from 'node:crypto';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const raw = readFileSync('protocol/model.json', 'utf8');
const spec = JSON.parse(raw);
const hash = createHash('sha256').update(raw).digest('hex');
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const variant = (name) => name.toUpperCase() === name
  ? name.toLowerCase().split('_').map((part) => part.replace(/^./, (c) => c.toUpperCase())).join('')
  : name.replace(/^./, (c) => c.toUpperCase());
function type(value, rust) {
  if (value.endsWith('?')) return rust ? `Option<${type(value.slice(0, -1), true)}>` : `${type(value.slice(0, -1), false)} | null`;
  if (value.endsWith('[]')) return rust ? `Vec<${type(value.slice(0, -2), true)}>` : `Array<${type(value.slice(0, -2), false)}>`;
  return ({ string: rust ? 'String' : 'string', bool: rust ? 'bool' : 'boolean', u8: rust ? 'u8' : 'number', u32: rust ? 'u32' : 'number', u64: rust ? 'u64' : 'number', f64: rust ? 'f64' : 'number' })[value] ?? value;
}
function supportsEq(name, seen = new Set()) {
  const base = name.replace(/\?|\[\]/g, '');
  if (base === 'f64') return false;
  if (!spec.structs[base] || seen.has(base)) return true;
  return Object.values(spec.structs[base]).every((field) => supportsEq(field, new Set([...seen, base])));
}
let ts = `// Generated by tools/generate-ipc.mjs; source SHA256 ${hash}\n`;
let rs = `// Generated by tools/generate-ipc.mjs; source SHA256 ${hash}\nuse serde::{Deserialize, Serialize};\n`;
for (const [name, values] of Object.entries(spec.enums)) {
  ts += `\nexport type ${name} = ${values.map((v) => JSON.stringify(v)).join(' | ')};\n`;
  rs += `\n#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]\npub enum ${name} {\n`;
  for (const value of values) rs += `    #[serde(rename = ${JSON.stringify(value)})]\n    ${variant(value)},\n`;
  rs += '}\n';
}
for (const [name, fields] of Object.entries(spec.structs)) {
  ts += `\nexport interface ${name} {\n`;
  rs += `\n#[derive(Clone, Debug, Serialize, Deserialize, PartialEq${supportsEq(name) ? ', Eq' : ''})]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct ${name} {\n`;
  for (const [field, value] of Object.entries(fields)) {
    ts += `  ${field}: ${type(value, false)};\n`;
    rs += `    pub ${snake(field)}: ${type(value, true)},\n`;
  }
  ts += '}\n'; rs += '}\n';
}
ts += '\nexport interface CommandArgs {\n';
for (const [name, fields] of Object.entries(spec.commands)) {
  ts += `  ${name}: { ${Object.entries(fields).map(([f, t]) => `${f}: ${type(t, false)}`).join('; ')} };\n`;
}
ts += '}\n';
ts += '\nexport interface CommandResults {\n';
for (const name of Object.keys(spec.commands)) {
  ts += `  ${name}: ${type(spec.commandResponses?.[name]?.typescript ?? 'AppSnapshot', false)};\n`;
}
ts += '}\n';
const outputs = { 'src/ipc/model.ts': ts, 'src-tauri/src/ipc/model.rs': rs };
let mismatch = false;
for (const [path, data] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* Missing output is a mismatch. */ }
    if (current !== data) { console.error(`FAIL IPC generation drift: ${path}`); mismatch = true; }
  } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, data); }
}
if (mismatch) process.exitCode = 1;
else console.log(`PASS IPC ${spec.version} ${hash.slice(0, 12)}`);
